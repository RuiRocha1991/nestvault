// pnpm gen:parser-schema          -> regenerates the zod schema of the parser service output
// pnpm gen:parser-schema --check  -> fails when the committed file is stale (CI)
// Source of truth: services/parser/schemas/rows.schema.json (generated from the pydantic models).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

import { jsonSchemaToZod } from 'json-schema-to-zod';
import { format, resolveConfig } from 'prettier';

const root = resolve(import.meta.dirname, '..');
const targets = [
  {
    source: resolve(root, 'services/parser/schemas/rows.schema.json'),
    target: resolve(root, 'packages/services/src/imports/parser-rows.generated.ts'),
    name: 'parserResponseSchema',
    from: 'rows.schema.json',
  },
  {
    source: resolve(root, 'services/parser/schemas/real-estate.schema.json'),
    target: resolve(root, 'packages/services/src/real-estate-imports/parser-rows.generated.ts'),
    name: 'realEstateResponseSchema',
    from: 'real-estate.schema.json',
  },
];

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

/**
 * json-schema-to-zod does not follow `$ref`, so inline them (the schema has no recursion). The
 * `oneOf` pydantic emits for the discriminated row union becomes `anyOf` -> `z.union`, which is
 * equivalent here because every variant has a distinct `kind` constant.
 */
function inline(node: Json, defs: Record<string, Json>): Json {
  if (Array.isArray(node)) return node.map((item) => inline(item, defs));
  if (node === null || typeof node !== 'object') return node;
  const ref = node['$ref'];
  if (typeof ref === 'string') {
    const target = defs[ref.replace('#/$defs/', '')];
    if (target === undefined) throw new Error(`Unresolved reference ${ref}`);
    return inline(target, defs);
  }
  const out: { [key: string]: Json } = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === '$defs' || key === 'discriminator') continue;
    out[key === 'oneOf' ? 'anyOf' : key] = inline(value, defs);
  }
  return out;
}

let stale = false;
for (const { source, target, name, from } of targets) {
  const document = JSON.parse(readFileSync(source, 'utf8')) as Record<string, Json> & {
    $defs: Record<string, Json>;
  };
  const schema = inline(document, document.$defs) as Record<string, unknown>;
  const body = jsonSchemaToZod(schema, { name, module: 'esm', type: true });
  const header =
    `// Generated by \`pnpm gen:parser-schema\` from services/parser/schemas/${from}.\n` +
    '// Do not edit by hand: change the pydantic models in services/parser and regenerate.\n';
  const options = (await resolveConfig(target)) ?? {};
  const next = await format(header + body, { ...options, filepath: target });

  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      // missing file counts as stale
    }
    if (current !== next) {
      console.error(`${target} is out of date: run \`pnpm gen:parser-schema\`.`);
      stale = true;
    }
  } else {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, next);
  }
}
if (stale) process.exit(1);
