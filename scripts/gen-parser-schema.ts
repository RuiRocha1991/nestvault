// pnpm gen:parser-schema          -> regenerates the zod schema of the parser service output
// pnpm gen:parser-schema --check  -> fails when the committed file is stale (CI)
// Source of truth: services/parser/schemas/rows.schema.json (generated from the pydantic models).
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { jsonSchemaToZod } from 'json-schema-to-zod';
import { format, resolveConfig } from 'prettier';

const root = resolve(import.meta.dirname, '..');
const source = resolve(root, 'services/parser/schemas/rows.schema.json');
const target = resolve(root, 'packages/services/src/imports/parser-rows.generated.ts');

type Json = null | boolean | number | string | Json[] | { [key: string]: Json };

const document = JSON.parse(readFileSync(source, 'utf8')) as Record<string, Json> & {
  $defs: Record<string, Json>;
};

/**
 * json-schema-to-zod does not follow `$ref`, so inline them (the schema has no recursion). The
 * `oneOf` pydantic emits for the discriminated row union becomes `anyOf` -> `z.union`, which is
 * equivalent here because every variant has a distinct `kind` constant.
 */
function inline(node: Json): Json {
  if (Array.isArray(node)) return node.map(inline);
  if (node === null || typeof node !== 'object') return node;
  const ref = node['$ref'];
  if (typeof ref === 'string') {
    const target = document.$defs[ref.replace('#/$defs/', '')];
    if (target === undefined) throw new Error(`Unresolved reference ${ref}`);
    return inline(target);
  }
  const out: { [key: string]: Json } = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === '$defs' || key === 'discriminator') continue;
    out[key === 'oneOf' ? 'anyOf' : key] = inline(value);
  }
  return out;
}

const schema = inline(document) as Record<string, unknown>;

const body = jsonSchemaToZod(schema, { name: 'parserResponseSchema', module: 'esm', type: true });
const header =
  '// Generated by `pnpm gen:parser-schema` from services/parser/schemas/rows.schema.json.\n' +
  '// Do not edit by hand: change the pydantic models in services/parser and regenerate.\n';
const options = (await resolveConfig(target)) ?? {};
const next = await format(header + body, { ...options, filepath: target });

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(target, 'utf8');
  } catch {
    // missing file counts as stale
  }
  if (current !== next) {
    console.error('parser-rows.generated.ts is out of date: run `pnpm gen:parser-schema`.');
    process.exit(1);
  }
} else {
  writeFileSync(target, next);
}
